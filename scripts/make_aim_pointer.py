#!/usr/bin/env python3
"""Builds the aim pointer picture from code (owner 2026-11-17: 'follow the reference picture, make it in SVG, then PNG, then GIF').
Design (the owner's reference: a neon chevron train, in RED since 2026-11-17): six right-pointing chevrons, outline and solid ones alternating, the last one a darker red, a layered glow under each. No SVG filters (the glow is
stacked strokes), so every renderer draws it the same: ImageMagick's own SVG renderer, a browser, the game canvas.
  python3 -B scripts/make_aim_pointer.py            writes assets/ui/aim_pointer.svg  (static, as the game draws it)
  python3 -B scripts/make_aim_pointer.py --demo DIR renders 12 flow frames to DIR as SVG and PNG (ImageMagick), and DIR/aim_pointer_flow.gif (a bright pulse running along the chevrons on a dark ground)
The picture is 480 x 96, drawn pointing right: the tail starts at x = 24 on the middle line (y = 48), the tip is at x = 464 (the game scales by length / 440 and rotates about the tail). Exit 1 on a failure."""
import argparse, math, os, subprocess, sys
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
N, PITCH, X0 = 6, 76.0, 24.0

def chevron(x):
    return "M%.1f 10 L%.1f 10 L%.1f 48 L%.1f 86 L%.1f 86 L%.1f 48 Z" % (x, x + 30, x + 58, x + 30, x, x + 28)

def svg(phase=None):
    """phase None: the static picture; a number 0..1: the pulse position for the flow frames."""
    out = ['<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 480 96" width="480" height="96">',
           '  <!-- Aim pointer, generated by scripts/make_aim_pointer.py (do not edit by hand). Pointing right; tail at (24, 48), tip at (464, 48). Neon chevron train after the owner\'s reference, glow made of stacked strokes. -->']
    for k in range(N):
        x = X0 + PITCH * k; solid = k % 2 == 1; last = k == N - 1
        boost = 1.0 if phase is None else 0.55 + 0.45 * max(0.0, math.cos(2 * math.pi * (phase - k / N)))
        col = "#b83a3a" if last else "#ff5252"
        d = chevron(x)
        for width, op in ((16, 0.10), (10, 0.18), (5, 0.34)):
            out.append('  <path d="%s" fill="none" stroke="%s" stroke-width="%d" stroke-opacity="%.2f" stroke-linejoin="round"/>' % (d, col, width, op * boost))
        if solid:
            out.append('  <path d="%s" fill="%s" fill-opacity="%.2f" stroke="#ffd0d0" stroke-opacity="%.2f" stroke-width="1.6" stroke-linejoin="round"/>' % (d, "#b83a3a" if last else "#ff6b6b", 0.55 + 0.45 * boost, 0.7 * boost))
        else:
            out.append('  <path d="%s" fill="#2a0808" fill-opacity="0.82" stroke="%s" stroke-opacity="%.2f" stroke-width="3.6" stroke-linejoin="round"/>' % (d, col, 0.6 + 0.4 * boost))
    out.append("</svg>")
    return "\n".join(out) + "\n"

def main():
    ap = argparse.ArgumentParser(); ap.add_argument("--demo"); a = ap.parse_args()
    with open(os.path.join(ROOT, "assets", "ui", "aim_pointer.svg"), "w") as f: f.write(svg())
    print("wrote assets/ui/aim_pointer.svg")
    if a.demo:
        os.makedirs(a.demo, exist_ok=True); from PIL import Image
        frames = []
        for i in range(12):
            base = os.path.join(a.demo, "flow_%02d" % i)
            with open(base + ".svg", "w") as f: f.write(svg(i / 12.0))
            r = subprocess.run(["magick", "-background", "none", "-density", "288", base + ".svg", base + ".png"], capture_output=True, text=True)
            if r.returncode: print("ERROR magick: " + r.stderr[:200], file=sys.stderr); sys.exit(1)
            im = Image.open(base + ".png").convert("RGBA"); bg = Image.new("RGBA", im.size, (5, 2, 10, 255)); bg.alpha_composite(im); frames.append(bg.convert("P", palette=Image.ADAPTIVE, colors=128))
        frames[0].save(os.path.join(a.demo, "aim_pointer_flow.gif"), save_all=True, append_images=frames[1:], duration=90, loop=0, disposal=2)
        print("wrote %s (%d frames, %s)" % (os.path.join(a.demo, "aim_pointer_flow.gif"), len(frames), frames[0].size))

if __name__ == "__main__":
    main()
