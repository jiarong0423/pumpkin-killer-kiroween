'use strict';
// Writes shared/determinism_golden.json from js/determinism.js (the reference). The Python port is then checked against it independently
// by scripts/test_determinism_golden.py. Run: node scripts/make_determinism_golden.js
const fs = require('fs');
const path = require('path');
const D = require(path.join(__dirname, '..', 'js', 'determinism.js'));
const seeds = [0, 1, 2, 7, 40, 81, 255, 1234567890, 2147483647, 4294967295, 99991, 31337, 424242];
const rounds = [1, 2, 3, 4, 10, 99];
const vectors = { wind: [], startX: [], moveDie: [], supplyDrop: [], bounceCount: [], nunStunPick: [], sideDraw: [], coinToss: [] };
for (const seed of seeds) {
  for (const coinSeed of [seed, (seed + 0x9e3779b9) >>> 0, (seed ^ 0xffffffff) >>> 0, (seed * 2654435761) >>> 0]) {
    vectors.sideDraw.push({ input: { seed: coinSeed }, output: D.sideDraw(coinSeed) });
    vectors.coinToss.push({ input: { seed: coinSeed }, output: D.coinToss(coinSeed) });
  }
  for (const round of rounds) {
    vectors.wind.push({ input: { seed, round }, output: D.wind(seed, round) });
    vectors.supplyDrop.push({ input: { seed, round }, output: D.supplyDrop(seed, round) });
  }
  for (const side of [0, 1]) {
    for (const slot of [0, 1, 2, 3]) {
      vectors.startX.push({ input: { seed, side, slot }, output: D.startX(seed, side, slot) });
    }
    for (const round of [1, 2, 3, 10]) {
      vectors.moveDie.push({ input: { seed, round, side }, output: D.moveDie(seed, round, side) });
    }
  }
  for (const round of [1, 2, 5]) {
    for (const throwId of [1, 2, 3, 4]) {
      vectors.bounceCount.push({ input: { seed, round, throwId }, output: D.bounceCount(seed, round, throwId) });
      for (const n of [1, 2, 3]) {
        vectors.nunStunPick.push({ input: { seed, round, throwId, n }, output: D.nunStunPick(seed, round, throwId, n) });
      }
    }
  }
}
const out = { version: 1, note: 'generated by scripts/make_determinism_golden.js from js/determinism.js; the Python port must reproduce every output', vectors };
fs.writeFileSync(path.join(__dirname, '..', 'shared', 'determinism_golden.json'), JSON.stringify(out, null, 1) + '\n');
console.log(Object.keys(vectors).map(k => k + ':' + vectors[k].length).join(' '));
