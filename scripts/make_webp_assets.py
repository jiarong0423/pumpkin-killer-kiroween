#!/usr/bin/env python3
"""Make WebP siblings of the big PNG pictures so the first page load is small (owner 2026-11-17: the first load fetched 27 MB of PNG on a phone).

For every PNG under assets/ of at least MIN_BYTES it writes <name>.webp next to it (lossy, quality 92, full alpha, method 4) when the WebP is smaller than 70 percent of the PNG,
and writes the list of the pictures that have a WebP to js/webp_manifest.js (loaded by index.html and by sw.js). The PNG files stay: they are the source and the fallback
for browsers without WebP. Nothing is ever deleted or overwritten except a stale .webp of the same name.

Usage: python3 -B scripts/make_webp_assets.py            write the files and the manifest
       python3 -B scripts/make_webp_assets.py --check    verify only (manifest equals the files on disk, every WebP has the PNG's size and alpha, PSNR >= 33 dB); exit 1 on a problem
Logs: logs_local/make_webp_assets.log. Exit code 1 on any failure.
"""
import argparse
import io
import json
import logging
import math
import os
import sys

from PIL import Image

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ASSETS = os.path.join(ROOT, "assets")
MANIFEST = os.path.join(ROOT, "js", "webp_manifest.js")
MIN_BYTES = 60 * 1024
QUALITY = 92
MAX_RATIO = 0.70
MIN_PSNR = 33.0
SKIP_DIRS = ("colab_inputs", "_replaced", "fonts")
os.makedirs(os.path.join(ROOT, "logs_local"), exist_ok=True)
logging.basicConfig(filename=os.path.join(ROOT, "logs_local", "make_webp_assets.log"), level=logging.INFO, format="%(asctime)s %(levelname)s %(message)s")


def png_files():
    out = []
    for base, dirs, files in os.walk(ASSETS):
        dirs[:] = [d for d in dirs if d not in SKIP_DIRS]
        for name in files:
            if name.lower().endswith(".png"):
                path = os.path.join(base, name)
                if os.path.getsize(path) >= MIN_BYTES:
                    out.append(path)
    return sorted(out)


def rel(path):
    return os.path.relpath(path, ROOT).replace(os.sep, "/")


def psnr(a, b):
    if a.size != b.size:
        return 0.0
    pa, pb = a.convert("RGBA").tobytes(), b.convert("RGBA").tobytes()
    n = len(pa)
    se = 0
    # compare on the colour of visible pixels (alpha above 8): fully transparent pixels hold no picture
    count = 0
    for i in range(0, n, 4):
        if pa[i + 3] > 8:
            for k in range(3):
                d = pa[i + k] - pb[i + k]
                se += d * d
            count += 3
    if count == 0 or se == 0:
        return 99.0
    return 10 * math.log10(255.0 * 255.0 / (se / count))


def convert(path):
    im = Image.open(path).convert("RGBA")
    buf = io.BytesIO()
    im.save(buf, "WEBP", quality=QUALITY, alpha_quality=100, method=4)
    return im, buf.getvalue()


def write_manifest(items):
    body = json.dumps(sorted(items), indent=1)
    text = ("/* GENERATED by scripts/make_webp_assets.py: the PNG pictures that have a .webp sibling (same path, .webp instead of .png), and assetUrl(path): the .webp path when this browser decodes WebP and the sibling exists, else the given path. Do not edit. */\n"
            "(function (root) {\n"
            "  root.PK_WEBP = " + body.replace("\n", "\n  ") + ";\n"
            "  var set = {}, ok = false;\n"
            "  root.PK_WEBP.forEach(function (p) { set[p] = 1; });\n"
            "  try { ok = typeof document !== 'undefined' && document.createElement('canvas').toDataURL('image/webp').indexOf('data:image/webp') === 0; } catch (e) { ok = false; }\n"
            "  root.assetUrl = function (p) {\n"
            "    if (!ok || typeof p !== 'string') return p;\n"
            "    var key = p.replace(/^\\.\\//, '');\n"
            "    return set[key] ? key.replace(/\\.png$/, '.webp') : p;\n"
            "  };\n"
            "})(typeof self !== 'undefined' ? self : window);\n")
    with open(MANIFEST, "w", encoding="utf-8") as fh:
        fh.write(text)


def read_manifest():
    if not os.path.exists(MANIFEST):
        return None
    text = open(MANIFEST, encoding="utf-8").read()
    start = text.index("PK_WEBP = ") + len("PK_WEBP = ")
    end = text.index("];", start) + 1
    return json.loads(text[start:end])


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    try:
        if args.check:
            listed = read_manifest()
            if listed is None:
                print("ERROR: js/webp_manifest.js is missing")
                return 1
            bad = 0
            for p in listed:
                png, webp = os.path.join(ROOT, p), os.path.join(ROOT, p[:-4] + ".webp")
                if not os.path.exists(png) or not os.path.exists(webp):
                    print("ERROR: missing file for", p); bad += 1; continue
                a, b = Image.open(png).convert("RGBA"), Image.open(webp).convert("RGBA")
                if a.size != b.size:
                    print("ERROR: size differs", p, a.size, b.size); bad += 1; continue
                if a.getextrema()[3][0] < 255 and b.getextrema()[3][0] == 255:
                    print("ERROR: alpha lost", p); bad += 1; continue
                q = psnr(a, b)
                if q < MIN_PSNR:
                    print("ERROR: PSNR %.1f dB below %.0f for %s" % (q, MIN_PSNR, p)); bad += 1
                if os.path.getsize(webp) > MAX_RATIO * os.path.getsize(png):
                    print("ERROR: webp not smaller enough", p); bad += 1
            on_disk = sorted(rel(w)[:-5] + ".png" for w in (os.path.join(b, f) for b, _, fs in os.walk(ASSETS) for f in fs if f.endswith(".webp")))
            if sorted(listed) != on_disk:
                print("ERROR: manifest and the .webp files on disk differ:", sorted(set(listed) ^ set(on_disk))[:5]); bad += 1
            print("check: %d pictures, %d problems" % (len(listed), bad))
            return 1 if bad else 0
        listed, png_bytes, webp_bytes = [], 0, 0
        for path in png_files():
            im, data = convert(path)
            webp_path = path[:-4] + ".webp"
            if len(data) > MAX_RATIO * os.path.getsize(path):
                if os.path.exists(webp_path):
                    os.remove(webp_path)   # a stale sibling of a picture that no longer compresses well
                continue
            with open(webp_path, "wb") as fh:
                fh.write(data)
            q = psnr(im, Image.open(webp_path).convert("RGBA"))
            if q < MIN_PSNR:
                # lossy is not good enough for this picture (soft glows, fine gradients): try lossless, which keeps every pixel
                buf = io.BytesIO()
                im.save(buf, "WEBP", lossless=True, method=4)
                data = buf.getvalue()
                if len(data) > MAX_RATIO * os.path.getsize(path):
                    os.remove(webp_path)
                    logging.warning("skipped %s: lossy PSNR %.1f dB and lossless not small enough", rel(path), q)
                    continue
                with open(webp_path, "wb") as fh:
                    fh.write(data)
                q = 99.0
            listed.append(rel(path))
            png_bytes += os.path.getsize(path)
            webp_bytes += len(data)
        write_manifest(listed)
        logging.info("wrote %d webp files: png %d bytes -> webp %d bytes", len(listed), png_bytes, webp_bytes)
        print("webp: %d pictures, PNG %.1f MB -> WebP %.1f MB (%.0f%% smaller); manifest js/webp_manifest.js" % (len(listed), png_bytes / 1e6, webp_bytes / 1e6, 100 * (1 - webp_bytes / max(1, png_bytes))))
        return 0
    except Exception as exc:  # noqa: BLE001 - one grep-able failure line
        logging.error("ERROR %s", exc)
        print("ERROR:", exc)
        return 1


if __name__ == "__main__":
    sys.exit(main())
