#!/usr/bin/env python3
"""Measure local relay join-to-first-accepted-action latency over 20 runs."""
import asyncio
import math
import os
import socket
import statistics
import subprocess
import sys
import time
from pathlib import Path
from typing import Any, Dict, List

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "scripts"))
from pk_relay_client import RelayClient  # noqa: E402

RUNS = 20


def free_port() -> int:
    with socket.socket(socket.AF_INET, socket.SOCK_STREAM) as listener:
        listener.bind(("127.0.0.1", 0))
        return int(listener.getsockname()[1])


async def wait_for_relay(port: int) -> None:
    for _ in range(100):
        try:
            reader, writer = await asyncio.open_connection("127.0.0.1", port)
            writer.close()
            await writer.wait_closed()
            return
        except OSError:
            await asyncio.sleep(0.02)
    raise RuntimeError("relay did not open its local port")


async def receive_type(client: RelayClient, wanted: str) -> Dict[str, Any]:
    for _ in range(20):
        message = await asyncio.wait_for(client.receive(), 1)
        if message.get("type") == wanted:
            return message
    raise RuntimeError("did not receive %s" % wanted)


async def one_run(url: str) -> float:
    host = RelayClient(url, None, "red")
    friend = None
    try:
        room = await host.connect()
        friend = RelayClient(url, room["code"], "white")
        started_at = time.perf_counter()
        await friend.connect()  # The measured join starts with this outbound message.
        await host.send({"type": "ready"})
        await friend.send({"type": "ready"})
        await receive_type(host, "start")
        await receive_type(friend, "start")
        await host.send({"type": "action", "round": 1, "phase": "red", "unit": "red_1",
                         "kind": "throw", "angle": 54, "power": 50})
        await receive_type(host, "action_ack")
        return (time.perf_counter() - started_at) * 1000
    finally:
        await host.close()
        if friend is not None:
            await friend.close()


def write_report(samples: List[float]) -> None:
    ordered = sorted(samples)
    p90 = ordered[math.ceil(len(ordered) * 0.90) - 1]
    report = "\n".join([
        "# Local relay join-time measurement",
        "",
        "Generated by `python3 -B scripts/measure_join_time.py` using loopback sockets.",
        "The machine field is intentionally recorded only as `local`.",
        "",
        "| runs | machine | median (ms) | p90 (ms) | min (ms) | max (ms) |",
        "| ---: | --- | ---: | ---: | ---: | ---: |",
        "| %d | local | %.2f | %.2f | %.2f | %.2f |" % (
            len(samples), statistics.median(samples), p90, min(samples), max(samples)),
        "",
        "Join time is measured from the friend's `join` send through the host receiving",
        "the relay's `action_ack` for the first legal throw. This is a local transport",
        "measurement, not a phone or internet latency claim.",
        "",
    ])
    (ROOT / "docs" / "join_time_20261116.md").write_text(report, encoding="utf-8")


async def main() -> None:
    port = free_port()
    environment = dict(os.environ, PORT=str(port), HOST="127.0.0.1")
    process = subprocess.Popen([sys.executable, "-B", str(ROOT / "scripts" / "pk_relay.py")],
                               cwd=str(ROOT), env=environment)
    try:
        await wait_for_relay(port)
        url = "ws://127.0.0.1:%d/ws" % port
        samples = [await one_run(url) for _ in range(RUNS)]
        write_report(samples)
        print("join-time runs=%d median_ms=%.2f" % (len(samples), statistics.median(samples)))
    finally:
        process.terminate()
        try:
            process.wait(timeout=5)
        except subprocess.TimeoutExpired:
            process.kill()
            process.wait(timeout=5)


if __name__ == "__main__":
    try:
        asyncio.run(main())
    except Exception as error:
        print("join-time failed: %s" % error, file=sys.stderr)
        raise SystemExit(1)
